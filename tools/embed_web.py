#!/usr/bin/env python3
"""Compresses web/index.html and writes it to src/web_page.h as a byte array.

Run after editing web/index.html:  python3 tools/embed_web.py
"""
import gzip

html = open("web/index.html", "rb").read()
gz = gzip.compress(html, compresslevel=9, mtime=0)
with open("src/web_page.h", "w") as f:
    f.write("// Generated by tools/embed_web.py from web/index.html - do not edit by hand.\n")
    f.write("#pragma once\n#include <Arduino.h>\n\n")
    f.write(f"static const size_t WEB_PAGE_GZ_LEN = {len(gz)};\n")
    f.write("static const uint8_t WEB_PAGE_GZ[] PROGMEM = {\n")
    for i in range(0, len(gz), 20):
        f.write("  " + ",".join(str(b) for b in gz[i:i + 20]) + ",\n")
    f.write("};\n")
print(f"index.html {len(html)} bytes -> {len(gz)} bytes gzipped")
